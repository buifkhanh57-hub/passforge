--- passforge/wordlist.lua
-- Embedded 1024-word English wordlist for the passphrase generator.
--
-- WHY 1024 WORDS
--   1024 = 2^10, so every word carries exactly log2(1024) = 10.00 bits of
--   entropy. A 4-word passphrase therefore has 40.00 bits, a 5-word one
--   50.00 bits - round numbers that make the entropy math in the README and
--   in `passforge pass --json` trivially verifiable. The passphrase module
--   reads the list size dynamically (wordlist.bits_per_word()), so even if
--   the list changes again the estimates stay correct.
--
-- CURATION
--   * 3-9 letters, common English, spread across the whole alphabet;
--   * no proper nouns beyond month names, no numerals, no profanity;
--   * no two entries differ only by a trailing "s" or "d" where avoidable,
--     to keep auto-complete-style human recall reliable;
--   * the list is alphabetically grouped; blocks of 16 words keep the file
--     diff-friendly (16 words = one display row in the audit tooling).
--
-- FORMAT
--   One word per line for easy diffing and easy counting. The module
--   enforces uniqueness at load time (a duplicate raises passforge.wordlist
--   error), and passphrase.lua reads the size dynamically via
--   wordlist.bits_per_word(), so the entropy estimates can never drift.

