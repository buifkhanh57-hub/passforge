-- Uniqueness is enforced at load time: a duplicated word would silently
-- shrink the keyspace while the entropy math kept assuming the full list.
local WORD_SET = {}
for i = 1, #WORDS do
  if WORD_SET[WORDS[i]] then
    compat.fail("wordlist", "duplicate word '%s' in embedded list", WORDS[i])
  end
  WORD_SET[WORDS[i]] = i
end

--- The full list as an array (copy-free: treat as read-only by convention).
function M.all()
  return WORDS
end

--- Number of embedded words (1024 in this release).
function M.count()
  return #WORDS
end

--- 1-based lookup, same contract as ipairs order; nil when out of range.
function M.at(i)
  return WORDS[i]
end

--- Case-insensitive membership test.
function M.contains(word)
  if type(word) ~= "string" then
    return false
  end
  return WORD_SET[word:lower()] ~= nil
end

--- 1-based index of word (case-insensitive) or nil.
function M.index_of(word)
  if type(word) ~= "string" then
    return nil
  end
  return WORD_SET[word:lower()]
end

--- Uniformly random word using the provided rng object (or the shared one).
function M.pick(rng)
  local source = rng or require("passforge.random").default()
  return WORDS[source:below(#WORDS) + 1]
end

--- Convenience alias used by the passphrase module.
M.random_word = M.pick

--- Bits of entropy per word: log2(#WORDS). For a 1024-word list this is
-- exactly 10.0; the passphrase module relies on that value dynamically so a
-- future word-list expansion keeps the math correct.
function M.bits_per_word()
  return compat.log2(#WORDS)
end

return M
